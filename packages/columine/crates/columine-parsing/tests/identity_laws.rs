//! Field identity bound to its proven model (specs/columine/laws/dictionary_binding.bend;
//! specs/columine/10-physical-vocabulary.md §6 "Field identity"): generated columns of `sb.fields`
//! identities run through the model's `identities_ok`, emitted into `identity_model.rs`, and
//! through `decode_field_identities` alike, and both accept the same schemas.

use std::rc::Rc;

use columine_parsing::identity::{IdentityError, decode_field_identities};
use proptest::prelude::*;
use sha2::{Digest, Sha256};

#[path = "identity_model.rs"]
mod model;

use model::{Ident, List};

/// One column's identities, each (library, number, type digest).
type Column = Vec<(u8, u8, u8)>;

fn list<T>(items: impl DoubleEndedIterator<Item = T>) -> Rc<List<T>> {
    items.rev().fold(Rc::new(List::Nil), |tail, head| {
        Rc::new(List::Con(head, tail))
    })
}

fn modelled(columns: &[Column]) -> bool {
    model::identities_ok(list(columns.iter().map(|column| {
        list(column.iter().map(|&(library, number, digest)| {
            Ident::Ident(library.into(), number.into(), digest.into())
        }))
    })))
}

/// The column's `sb.fields` value; a column with no identity carries no key.
fn metadata(column: &Column) -> Option<String> {
    (!column.is_empty()).then(|| {
        let entries: Vec<String> = column
            .iter()
            .map(|&(library, number, digest)| {
                format!(r#"{{"lib":"lib{library}","n":{number},"name":"f","type":"t{digest}"}}"#)
            })
            .collect();
        format!("[{}]", entries.join(","))
    })
}

fn decoded(columns: &[Column]) -> bool {
    let metadata: Vec<Option<String>> = columns.iter().map(metadata).collect();
    match decode_field_identities(&metadata) {
        Ok(_) => true,
        Err(IdentityError::TwoTypes { .. } | IdentityError::Repeated { .. }) => false,
        Err(other) => panic!("decoding refused for a reason the model does not state: {other:?}"),
    }
}

/// The model module names the law file it was emitted from by its sha256, so a law file that
/// moved since fails here, naming the command that emits the module again.
#[test]
fn the_model_is_emitted_from_the_law_file_in_the_tree() {
    let module = include_str!("identity_model.rs");
    let header = |prefix: &str| {
        module
            .lines()
            .find_map(|line| line.strip_prefix(prefix))
            .unwrap_or_else(|| panic!("the model module's header has no `{prefix}` line"))
    };
    let generator = header("// GENERATED by ");
    let recorded = header("// model sha256: ");
    // Compiled in, so the law file is an input of this test's build and of its cache key.
    let law = include_bytes!("../../../../../specs/columine/laws/dictionary_binding.bend");
    let actual: String = Sha256::digest(law)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    assert_eq!(
        actual, recorded,
        "specs/columine/laws/dictionary_binding.bend moved since the model was emitted: from the \
         repository root run `{generator}`, and put its module at \
         packages/columine/crates/columine-parsing/tests/identity_model.rs under the two header \
         lines, with this sha256"
    );
}
//#region smoo/columine!n/vocab-field-identity

proptest! {
    /// Decoding accepts exactly the schemas the model accepts: each column of one type digest,
    /// each (lib, n) named at one entry of one column.
    #[test]
    fn decoding_accepts_identities_as_the_model_does(
        columns in prop::collection::vec(
            prop::collection::vec((0_u8..=2, 0_u8..=2, 0_u8..=2), 0..3),
            0..5,
        ),
    ) {
        prop_assert_eq!(decoded(&columns), modelled(&columns));
    }
}

