/// The model's aging bound in ticks of one second: the sim's [`AGING`].
const BOUND: u32 = 30;

fn crate_dir() -> PathBuf {
    PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo runs a test with CARGO_MANIFEST_DIR"),
    )
}

/// The kernel names the model it was emitted from by its sha256, so a model that moved since
/// fails here, naming the command that emits the kernel again.
#[test]
fn the_kernel_is_emitted_from_the_model_in_the_tree() {
    let dir = crate_dir();
    let kernel =
        std::fs::read_to_string(dir.join("src/bend_admission.rs")).expect("the kernel reads");
    let header = |prefix: &str| {
        kernel
            .lines()
            .find_map(|line| line.strip_prefix(prefix))
            .unwrap_or_else(|| panic!("the kernel's header has no `{prefix}` line"))
    };
    let generator = header("// GENERATED by ");
    let recorded = header("// model sha256: ");
    let model = std::fs::read(dir.join("../../../../specs/cowshed/laws/admission.bend"))
        .expect("the model reads");
    let actual: String = Sha256::digest(&model)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    assert_eq!(
        actual, recorded,
        "specs/cowshed/laws/admission.bend moved since the kernel was emitted: from the repository \
         root run `{generator}`, and put its admission.rs at \
         packages/cowshed/crates/cowshed-admission-sim/src/bend_admission.rs under the two header \
         lines, with this sha256"
    );
}

/// One step of a trace.
#[derive(Clone, Copy, Debug)]
enum Act {
    /// A request of `band`, for `want` cores, predicted `pred` s, from a job that has run
    /// `elapsed` s: the age an interactive request's band decays by.
    Arrive {
        band: Declares,
        want: u32,
        pred: u32,
        elapsed: u32,
    },
    /// One pool decision.
    Decide,
    /// This many ticks of one second each.
    Tick(u32),
    /// The end of the request that arrived `pick`-th, modulo the arrivals so far: a grant's end
    /// gives its cores back, and a waiting request's withdraws it.
    Finish(u64),
}

/// The band a request declares, as the model's `Band` names it.
#[derive(Clone, Copy, Debug)]
enum Declares {
    Gate,
    Interactive,
    Background,
}

impl Declares {
    fn model(self) -> Band {
        match self {
            Self::Gate => Band::Gate,
            Self::Interactive => Band::Interactive,
            Self::Background => Band::Background,
        }
    }

    /// The sim's declaration of an ask at `asked` from a job that has run `elapsed`.
    fn sim(self, asked: Secs, elapsed: u32) -> Declared {
        match self {
            Self::Gate => Declared::Normal,
            Self::Interactive => Declared::Interactive {
                job_started: asked - Secs::from(elapsed),
            },
            Self::Background => Declared::Low,
        }
    }
}

fn act() -> impl Strategy<Value = Act> {
    let band = prop_oneof![
        Just(Declares::Gate),
        Just(Declares::Interactive),
        Just(Declares::Background),
    ];
    prop_oneof![
        4 => (band, 1..=4_u32, 1..=600_u32, 0..=300_u32)
            .prop_map(|(band, want, pred, elapsed)| Act::Arrive { band, want, pred, elapsed }),
        3 => Just(Act::Decide),
        2 => (1..=BOUND).prop_map(Act::Tick),
        2 => any::<u64>().prop_map(Act::Finish),
    ]
}

/// The sim's pool as the model sees it: one domain, moldable requests, no memory.
#[derive(Debug, Default)]
struct Pool {
    queue: Vec<(u64, Request)>,
    leases: BTreeMap<u64, u32>,
    now: Secs,
}

impl Pool {
    fn arrive(&mut self, id: u64, declared: Declared, want: u32, pred: u32) {
        let class = match declared {
            Declared::Interactive { .. } => Class::Interactive,
            Declared::Normal => Class::Gate,
            Declared::Low => Class::Background,
        };
        let request = Request {
            ticket: id,
            class,
            priority: declared.band(self.now),
            since: self.now,
            rank: 0.0,
            predicted: Some(Secs::from(pred)),
            kind: Kind::Reservation,
            charge: Charge {
                cpus: want,
                memory: 0,
            },
        };
        self.queue.push((id, request));
    }

    /// One [`POOL_RULE`] pass: each request it grants, with its cores.
    fn decide(&mut self, cap: u32) -> BTreeMap<u64, u64> {
        let requests: Vec<Request> = self.queue.iter().map(|&(_, request)| request).collect();
        let live: Vec<Lease> = self
            .leases
            .values()
            .map(|&cpus| Lease {
                charge: Charge { cpus, memory: 0 },
                ends: self.now,
            })
            .collect();
        let cap = Charge {
            cpus: cap,
            memory: 0,
        };
        let mut grants = admit::admit(POOL_RULE, &requests, &live, cap, self.now);
        grants.sort_by_key(|grant| Reverse(grant.index));
        grants
            .into_iter()
            .map(|grant| {
                let (id, _) = self.queue.remove(grant.index);
                self.leases.insert(id, grant.charge.cpus);
                (id, u64::from(grant.charge.cpus))
            })
            .collect()
    }

    fn finish(&mut self, id: u64) {
        self.queue.retain(|&(waiting, _)| waiting != id);
        self.leases.remove(&id);
    }
}

/// Every request the model's state holds a grant for, with its cores.
fn granted(state: &St) -> BTreeMap<u64, u64> {
    let St::St(_, _, lanes) = state;
    let mut granted = BTreeMap::new();
    let mut lane: &List<Lane> = lanes;
    while let List::Con(Lane::Lane(old, new), rest) = lane {
        for list in [old, new] {
            let mut at: &List<E> = list;
            while let List::Con(E::E(id, _, k, _, _, _, _), rest) = at {
                if *k > 0 {
                    granted.insert(*id, *k);
                }
                at = rest;
            }
        }
        lane = rest;
    }
    granted
}

/// The model's `empty(cap, bound)`: a pool of `cap` permits and one empty lane per band.
fn empty(cap: u32) -> St {
    let lanes = (0..3).fold(Rc::new(List::Nil), |rest, _| {
        Rc::new(List::Con(
            Lane::Lane(List::Nil.into(), List::Nil.into()),
            rest,
        ))
    });
    St::St(u64::from(cap), u64::from(BOUND), lanes)
}

/// The model's lane index of a sim band, in the order of its `lane(band, elapsed)`.
fn lane(band: Priority) -> u64 {
    match band {
        Priority::Interactive => 0,
        Priority::Normal => 1,
        Priority::Low => 2,
    }
}

/// Every item of a model list, in order.
fn items<T: Clone>(list: &Rc<List<T>>) -> Vec<T> {
    let mut out = Vec::new();
    let mut at: &List<T> = list;
    while let List::Con(head, rest) = at {
        out.push(head.clone());
        at = rest;
    }
    out
}

/// The model's `AllFilled`: no request of `list` needs another permit.
fn all_filled(list: &Rc<List<E>>) -> bool {
    items(list).into_iter().all(|entry| bend::need(entry) == 0)
}

/// The free permits and the three lanes of a state of the pool `empty` makes: interactive, the
/// gate's and low.
fn lanes(state: &St) -> (u64, [Lane; 3]) {
    let St::St(free, _, lanes) = state;
    let lanes: [Lane; 3] = items(lanes)
        .try_into()
        .unwrap_or_else(|_| panic!("the pool `empty` makes has three lanes"));
    (*free, lanes)
}

/// The model's `WaitsLs(free, lanes, [])`: re-examined in pass order with what is left `free`,
/// each lane's aged requests are filled unless it is the low lane behind an open gather, and each
/// request in `new`, given its turn again, takes nothing more.
fn only_gathers_hold_back(free: u64, lanes: &[Lane; 3]) -> bool {
    let mut gathers: Rc<List<u64>> = Rc::new(List::Nil);
    for (at, Lane::Lane(old, new)) in lanes.iter().enumerate() {
        let low = at + 1 == lanes.len();
        if !(all_filled(old) || bend::skip(low, gathers.clone())) {
            return false;
        }
        for E::E(_, want, k, _, _, min, party) in items(new) {
            let act = bend::act(low, gathers.clone(), k, want, min, party, free);
            if act == bend::Act::Take && bend::need_k(want, k) != 0 {
                return false;
            }
            gathers = bend::gnext(act, party, gathers);
        }
    }
    true
}

/// The model's `gate_waits_only_for_admitted_work_or_a_gather` on the decision from `before` to
/// `after`: every gate request is filled, or the low lane is as it was and no permit is free or
/// every request still waiting is held back by a gather.
fn gate_waits_only_for_admitted_work_or_a_gather(before: &St, after: &St) -> bool {
    let (_, [_, _, low_before]) = lanes(before);
    let (free, lanes_after) = lanes(after);
    let [_, Lane::Lane(gate_old, gate_new), low] = &lanes_after;
    (all_filled(gate_old) && all_filled(gate_new))
        || (*low == low_before && (free == 0 || only_gathers_hold_back(free, &lanes_after)))
}

/// The law as it holds without minimums (`gate_waits_only_for_admitted_work_refuted` refutes it
/// with one): every gate request is filled, or the low lane is as it was and no permit is free.
fn gate_waits_only_for_admitted_work(before: &St, after: &St) -> bool {
    let (_, [_, _, low_before]) = lanes(before);
    let (free, [_, Lane::Lane(gate_old, gate_new), low]) = lanes(after);
    (all_filled(&gate_old) && all_filled(&gate_new)) || (low == low_before && free == 0)
}

/// Runs `acts` through the model's kernel alone, each arrival naming the minimum and party drawn
/// with it (the simulator names neither), and holds
/// `gate_waits_only_for_admitted_work_or_a_gather` after every decision.
fn drive_gathers(cap: u32, acts: &[(Act, u32, u32)]) -> Result<(), TestCaseError> {
    let mut model = empty(cap);
    let mut arrived = 0_u64;
    for (at, &(act, min, party)) in acts.iter().enumerate() {
        model = match act {
            Act::Arrive {
                band,
                want,
                pred,
                elapsed,
            } => {
                arrived += 1;
                let op = Op::Arrive(
                    band.model(),
                    arrived,
                    u64::from(want - 1),
                    u64::from(pred),
                    u64::from(elapsed),
                    u64::from(min),
                    u64::from(party),
                );
                bend::step(Pol::Spt, op, model)
            }
            Act::Decide => {
                let after = bend::step(Pol::Spt, Op::Decide, model.clone());
                prop_assert!(
                    gate_waits_only_for_admitted_work_or_a_gather(&model, &after),
                    "act {} left a gate request waiting for neither admitted work nor a gather: \
                     the model was {} and is now {}",
                    at,
                    bend::show_St(&model),
                    bend::show_St(&after)
                );
                after
            }
            Act::Tick(ticks) => {
                (0..ticks).fold(model, |state, _| bend::step(Pol::Spt, Op::Tick, state))
            }
            Act::Finish(pick) if arrived > 0 => {
                bend::step(Pol::Spt, Op::Finish(pick % arrived + 1), model)
            }
            Act::Finish(_) => model,
        };
    }
    Ok(())
}
/// Runs `acts` on a pool of `cap` cores through the model's `step(Spt, …)` and the sim's pool
/// rule, and holds that every decision grants the same requests the same cores in both.
fn drive(cap: u32, acts: &[Act]) -> Result<(), TestCaseError> {
    prop_assert_eq!(AGING, Secs::from(BOUND));
    let mut model = empty(cap);
    let mut pool = Pool::default();
    let mut arrived = 0_u64;
    for (at, &act) in acts.iter().enumerate() {
        match act {
            Act::Arrive {
                band,
                want,
                pred,
                elapsed,
            } => {
                arrived += 1;
                // The model's `Arrive` asks for one more than its `want`, so none asks for none.
                let op = Op::Arrive(
                    band.model(),
                    arrived,
                    u64::from(want - 1),
                    u64::from(pred),
                    u64::from(elapsed),
                    // The simulator names no minimum: the model decides as today when none
                    // does (`min_le_one_is_today`).
                    0,
                    0,
                );
                let declared = band.sim(pool.now, elapsed);
                prop_assert_eq!(
                    lane(declared.band(pool.now)),
                    bend::lane(band.model(), u64::from(elapsed)),
                    "act {} entered another lane",
                    at
                );
                model = bend::step(Pol::Spt, op, model);
                pool.arrive(arrived, declared, want, pred);
            }
            Act::Decide => {
                let prior = model.clone();
                let before = granted(&model);
                model = bend::step(Pol::Spt, Op::Decide, model);
                // The simulator names no minimum, so no gather opens.
                prop_assert!(
                    gate_waits_only_for_admitted_work(&prior, &model),
                    "act {} left a gate request waiting beside a free permit or a low grant: the \
                     model was {} and is now {}",
                    at,
                    bend::show_St(&prior),
                    bend::show_St(&model)
                );
                let mut by_model = granted(&model);
                by_model.retain(|id, _| !before.contains_key(id));
                let by_sim = pool.decide(cap);
                prop_assert_eq!(
                    &by_model,
                    &by_sim,
                    "act {} decided differently: the model granted {:?}, the sim {:?}; the model \
                     is now {} and the sim's queue {:?}",
                    at,
                    &by_model,
                    &by_sim,
                    bend::show_St(&model),
                    &pool.queue
                );
            }
            Act::Tick(ticks) => {
                for _ in 0..ticks {
                    model = bend::step(Pol::Spt, Op::Tick, model);
                    pool.now += 1.0;
                }
            }
            Act::Finish(pick) => {
                if arrived > 0 {
                    let id = pick % arrived + 1;
                    model = bend::step(Pol::Spt, Op::Finish(id), model);
                    pool.finish(id);
                }
            }
        }
    }
    Ok(())
}

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 2048,
        rng_seed: RngSeed::Fixed(0x5EED_0AD3_1551_0000),
        ..ProptestConfig::default()
    })]

    /// Seeded random traces of arrivals to the three bands, decisions, ticks and ends, on pools of
    /// 1 to 18 cores: after every decision the model's kernel and the sim's pool rule have granted
    /// the same requests the same cores. A mismatch prints the shrunk trace.
    #[test]
    fn the_pool_rule_decides_as_the_proven_model(
        cap in 1..=18_u32,
        acts in prop::collection::vec(act(), 0..=40),
    ) {
        drive(cap, &acts)?;
    }

    /// Seeded random traces whose requests name a minimum of 0 to 5 cores and a party of 0 to 2,
    /// on pools of 1 to 8 cores, through the model's kernel: after every decision every gate
    /// request is filled, or the low lane is as it was and no permit is free or every request
    /// still waiting is held back by a gather.
    #[test]
    fn a_gate_waits_only_for_admitted_work_or_a_gather(
        cap in 1..=8_u32,
        acts in prop::collection::vec((act(), 0..=5_u32, 0..=2_u32), 0..=40),
    ) {
        drive_gathers(cap, &acts)?;
    }
}

/// The sim's decay bounds are the model's `b1()` and `b2()`, and an interactive ask takes the
/// model's band (`iband`) at every age from 0 to 300 s.
#[test]
fn an_interactive_ask_decays_at_the_models_bounds() {
    let secs = |n: u64| Secs::from(u32::try_from(n).expect("a bound fits u32"));
    assert_eq!(secs(bend::b1()), DECAY.interactive_for);
    assert_eq!(secs(bend::b2()), DECAY.normal_until);
    for elapsed in 0..=300_u32 {
        let sim = (Declared::Interactive { job_started: 0.0 }).band(Secs::from(elapsed));
        assert_eq!(lane(sim), bend::iband(u64::from(elapsed)), "at {elapsed} s");
    }
}

/// Round 9 through the kernel (`gate_waits_only_for_admitted_work_refuted`): on a pool of 4 a gate
/// job holds 3, and a gate reservation asks 18 with a minimum of 4 (party 1). The decision leaves
/// it gathering beside a free permit: it waits for its own gather, not for admitted work.
#[test]
fn a_gathering_gate_request_waits_beside_a_free_permit() {
    let before = [
        Op::Arrive(Band::Gate, 1, 2, 5, 0, 0, 0),
        Op::Decide,
        Op::Arrive(Band::Gate, 2, 17, 9, 0, 4, 1),
    ]
    .into_iter()
    .fold(empty(4), |state, op| bend::step(Pol::Spt, op, state));
    let after = bend::step(Pol::Spt, Op::Decide, before.clone());
    assert!(
        !gate_waits_only_for_admitted_work(&before, &after),
        "{}",
        bend::show_St(&after)
    );
    assert!(
        gate_waits_only_for_admitted_work_or_a_gather(&before, &after),
        "{}",
        bend::show_St(&after)
    );
}
