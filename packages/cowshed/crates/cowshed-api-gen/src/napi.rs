    /// One `Serves` impl in the generated file, from its header through its closing brace.
    fn served_impl<'a>(served: &'a str, operation: &str, class: &str) -> &'a str {
        let header = format!("impl Serves<{operation}> for {class} {{");
        let start = served
            .find(&header)
            .unwrap_or_else(|| panic!("{class} serves {operation}:\n{served}"));
        let rest = &served[start..];
        rest.find("\n}\n").map_or(rest, |end| &rest[..end + 2])
    }

    /// A read-only reference fences its repository and workspace, not the incarnation it was
    /// resolved at. It binds that incarnation all the same: a request that requires one carries
    /// it, and one that leaves it optional sends it absent while keeping it bound, so no caller
    /// names it. A worker fences its whole incarnation and always sends it.
    #[test]
    fn a_reference_sends_an_optional_incarnation_absent_while_a_worker_holds_it() {
        let output = output(
            r#"operations! {
                /// Reads one workspace's grants.
                worker json "workspace.grants" WorkspaceGrants(GrantsRequest) -> EmptyResult;
                /// The build volume a job of the workspace incarnation would be granted now.
                coordinator json "workspace.buildVolume" WorkspaceBuildVolume(WorkerScope) -> EmptyResult;
            }"#,
        )
        .expect("projection");
        let served = &output.served;
        let bound = r#"const BOUND: &'static [&'static str] = &["repoId", "workspace", "workspaceIncarnation"];"#;
        for (operation, class, construction, absent) in [
            (
                "WorkspaceGrants",
                "WorkspaceRef",
                "Ok(GrantsRequest { repo_id: owned(authority.repo_id), workspace: owned(authority.workspace), workspace_incarnation: None })",
                r#"workspace_ref, &["workspaceIncarnation"]"#,
            ),
            (
                "WorkspaceGrants",
                "WorkspaceHandle",
                "Ok(GrantsRequest { repo_id: owned(authority.repo_id), workspace: owned(authority.workspace), workspace_incarnation: Some(owned(authority.workspace_incarnation)) })",
                "workspace_handle, &[]",
            ),
            (
                "WorkspaceBuildVolume",
                "WorkspaceRef",
                "Ok(WorkerScope { repo_id: owned(authority.repo_id), workspace: owned(authority.workspace), workspace_incarnation: owned(authority.workspace_incarnation) })",
                "workspace_ref, &[]",
            ),
        ] {
            let implementation = served_impl(served, operation, class);
            assert!(implementation.contains(bound), "{implementation}");
            assert!(implementation.contains(construction), "{implementation}");
            assert!(
                served.contains(&format!("    check.served::<{operation}, _>({absent});")),
                "{served}"
            );
        }
        assert!(
            !served.contains("impl Serves<WorkspaceBuildVolume> for WorkspaceHandle"),
            "{served}"
        );
        assert!(
            output.typescript.contains(
                "export type WorkspaceGrantsArguments = Readonly<Record<string, never>>;"
            ),
            "{}",
            output.typescript
        );
    }

