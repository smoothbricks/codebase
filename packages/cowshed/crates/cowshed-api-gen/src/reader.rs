//! The reader projection of every operation result (07_api.md, "Reader projection"): writers
//! are strict and readers project. One rule: a
//! client reads a peer's result or event through the object members its declaration names, and
//! drops every other key before the strict decode certifies it; a request is never projected.
//! The readers resolve each declaration exactly as its TypeScript projection does, so the Rust
//! client and the TypeScript validators drop the same keys.

use crate::ir::{Api, Field, Fields, Record, RustType, Shape, Variant, last_segment};
use crate::napi::{ResultShape, operation_result_record};
use crate::operations::{Operation, Scope};
use crate::typescript::{primitive_projection, renamed, type_arguments};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

const HEADER: &str =
    "// Generated by cowshed-api-gen from cowshed-core's operation table. Do not edit.\n";

/// The static every reader of a value without declared members is.
const LEAF: &str = "LEAF";

/// The members of one object: each wire name with the static its value is read through.
type Members = Vec<(String, String)>;

/// One generated `Reader` value, its references named by the statics they are.
#[derive(Debug, PartialEq, Eq)]
enum Node {
    Leaf,
    Seq(String),
    Map(String),
    Tuple(Vec<String>),
    Record(Members),
    External(Vec<(String, String)>),
    Internal {
        tag: String,
        arms: Vec<(String, String)>,
    },
    Adjacent {
        tag: String,
        content: String,
        arms: Vec<(String, String)>,
    },
    Untagged(Vec<Members>),
}

/// The readers reachable from a set of declarations, one static each.
pub struct Readers<'a> {
    api: &'a Api,
    /// The static a record's own node is, reserved before its members so a recursive record
    /// names itself.
    records: BTreeMap<String, String>,
    statics: BTreeMap<String, Node>,
}

impl<'a> Readers<'a> {
    pub fn new(api: &'a Api) -> Self {
        Self {
            api,
            records: BTreeMap::new(),
            statics: BTreeMap::from([(LEAF.to_owned(), Node::Leaf)]),
        }
    }

    /// Whether the declaration's value holds no declared object: nothing to drop when reading it.
    pub fn is_leaf(&mut self, record: &str) -> Result<bool, String> {
        Ok(self.record(record)? == LEAF)
    }

    /// The static `record`'s value is read through.
    fn record(&mut self, name: &str) -> Result<String, String> {
        if let Some(reader) = self.records.get(name) {
            return Ok(reader.clone());
        }
        let api = self.api;
        let record = api
            .records
            .get(name)
            .ok_or_else(|| format!("API type {name} has no declaration"))?;
        if record.projection.scalar.is_some() {
            return Ok(LEAF.to_owned());
        }
        if let Some(proxy) = record
            .projection
            .wire
            .as_ref()
            .or(record.serde.into.as_ref())
            .or(record.serde.from.as_ref())
        {
            let proxy = RustType::parse(proxy)
                .map_err(|error| format!("{name}: invalid serde proxy: {error}"))?;
            return self.ty(&proxy);
        }
        match &record.shape {
            Shape::Alias(ty) => self.ty(ty),
            Shape::Struct(Fields::Unit) => Ok(LEAF.to_owned()),
            Shape::Struct(Fields::Named(fields) | Fields::Tuple(fields))
                if record.serde.transparent =>
            {
                match projected(fields).as_slice() {
                    [field] => self.ty(&field.ty),
                    _ => Err(format!(
                        "{name}: transparent record requires one projected field"
                    )),
                }
            }
            Shape::Struct(Fields::Tuple(fields)) => match projected(fields).as_slice() {
                [field] => self.ty(&field.ty),
                fields => {
                    let reader = self.reserve(name)?;
                    let positions = fields
                        .iter()
                        .map(|field| self.ty(&field.ty))
                        .collect::<Result<_, _>>()?;
                    self.define(reader, Node::Tuple(positions))
                }
            },
            Shape::Struct(Fields::Named(fields)) => {
                let reader = self.reserve(name)?;
                let members = self.members(fields, record.serde.rename_all.as_deref())?;
                self.define(reader, Node::Record(members))
            }
            Shape::Enum(variants) => {
                let reader = self.reserve(name)?;
                let node = self.enumeration(record, variants)?;
                self.define(reader, node)
            }
        }
    }

    fn reserve(&mut self, record: &str) -> Result<String, String> {
        let reader = renamed(record, None, Some("SCREAMING_SNAKE_CASE"))?;
        if reader == LEAF || self.statics.contains_key(&reader) {
            return Err(format!(
                "{record}: its reader static {reader} is already another reader's name"
            ));
        }
        self.records.insert(record.to_owned(), reader.clone());
        Ok(reader)
    }

    /// Publishes `node` as `reader`. A name derived from what it reads is defined once.
    fn define(&mut self, reader: String, node: Node) -> Result<String, String> {
        match self.statics.get(&reader) {
            Some(existing) if *existing == node => Ok(reader),
            Some(_) => Err(format!("two different readers are named {reader}")),
            None => {
                self.statics.insert(reader.clone(), node);
                Ok(reader)
            }
        }
    }

    fn enumeration(&mut self, record: &Record, variants: &[Variant]) -> Result<Node, String> {
        let name = &record.name;
        let serde = &record.serde;
        let mut arms = Vec::with_capacity(variants.len());
        for variant in variants.iter().filter(|variant| !variant.serde.skip) {
            let arm = renamed(
                &variant.name,
                variant.serde.rename.as_deref(),
                serde.rename_all.as_deref(),
            )?;
            let rename_fields = variant
                .serde
                .rename_all
                .as_deref()
                .or(serde.rename_all_fields.as_deref());
            arms.push((arm, variant, rename_fields));
        }
        if serde.untagged {
            let mut objects = Vec::with_capacity(arms.len());
            for (arm, variant, rename_fields) in arms {
                match &variant.fields {
                    Fields::Unit => {}
                    Fields::Named(fields) => objects.push(self.members(fields, rename_fields)?),
                    Fields::Tuple(fields) => match projected(fields).as_slice() {
                        [field] => {
                            let reader = self.ty(&field.ty)?;
                            match self.statics.get(&reader) {
                                Some(Node::Leaf) => {}
                                Some(Node::Record(members)) => objects.push(members.clone()),
                                _ => {
                                    return Err(format!(
                                        "{name}::{arm}: an untagged arm is read as an object of named members or a scalar"
                                    ));
                                }
                            }
                        }
                        _ => {
                            return Err(format!(
                                "{name}::{arm}: an untagged arm of several positions has no reader"
                            ));
                        }
                    },
                }
            }
            return Ok(Node::Untagged(objects));
        }
        match (&serde.tag, &serde.content) {
            (Some(tag), Some(content)) => {
                let mut readers = Vec::with_capacity(arms.len());
                for (arm, variant, rename_fields) in arms {
                    let reader = self.content(name, &arm, &variant.fields, rename_fields)?;
                    readers.push((arm, reader));
                }
                Ok(Node::Adjacent {
                    tag: tag.clone(),
                    content: content.clone(),
                    arms: readers,
                })
            }
            (Some(tag), None) => {
                let mut objects = Vec::with_capacity(arms.len());
                for (arm, variant, rename_fields) in arms {
                    let reader = match &variant.fields {
                        Fields::Unit => self.define(
                            format!(
                                "{}__{}",
                                renamed(name, None, Some("SCREAMING_SNAKE_CASE"))?,
                                renamed(&arm, None, Some("SCREAMING_SNAKE_CASE"))?
                            ),
                            Node::Record(Vec::new()),
                        )?,
                        fields => self.content(name, &arm, fields, rename_fields)?,
                    };
                    if !matches!(
                        self.statics.get(&reader),
                        Some(Node::Record(_) | Node::Untagged(_))
                    ) {
                        return Err(format!(
                            "{name}::{arm}: an internally tagged arm is read as an object"
                        ));
                    }
                    objects.push((arm, reader));
                }
                Ok(Node::Internal {
                    tag: tag.clone(),
                    arms: objects,
                })
            }
            (None, Some(_)) => Err(format!("{name}: serde content without a tag")),
            (None, None) => {
                let mut readers = Vec::with_capacity(arms.len());
                for (arm, variant, rename_fields) in arms {
                    let reader = self.content(name, &arm, &variant.fields, rename_fields)?;
                    readers.push((arm, reader));
                }
                Ok(Node::External(readers))
            }
        }
    }

    /// The static one variant's content is read through.
    fn content(
        &mut self,
        record: &str,
        arm: &str,
        fields: &Fields,
        rename_fields: Option<&str>,
    ) -> Result<String, String> {
        match fields {
            Fields::Unit => Ok(LEAF.to_owned()),
            Fields::Named(fields) => {
                let members = self.members(fields, rename_fields)?;
                let reader = format!(
                    "{}__{}",
                    renamed(record, None, Some("SCREAMING_SNAKE_CASE"))?,
                    renamed(arm, None, Some("SCREAMING_SNAKE_CASE"))?
                );
                self.define(reader, Node::Record(members))
            }
            Fields::Tuple(fields) => match projected(fields).as_slice() {
                [field] => self.ty(&field.ty),
                fields => {
                    let positions = fields
                        .iter()
                        .map(|field| self.ty(&field.ty))
                        .collect::<Result<Vec<_>, _>>()?;
                    let reader = format!("TUPLE__{}", positions.join("__"));
                    self.define(reader, Node::Tuple(positions))
                }
            },
        }
    }

    /// An object's members by wire name, flattened members included. A name two members claim
    /// with different readers is refused.
    fn members(&mut self, fields: &[Field], rename_all: Option<&str>) -> Result<Members, String> {
        let mut members = Vec::with_capacity(fields.len());
        for field in projected(fields) {
            if field.serde.flatten {
                for member in self.flattened(&field.ty)? {
                    claim(&mut members, member)?;
                }
                continue;
            }
            let rust = field.name.as_deref().ok_or("named field lacks a name")?;
            let name = renamed(rust, field.serde.rename.as_deref(), rename_all)?;
            let reader = self.ty(&field.ty)?;
            claim(&mut members, (name, reader))?;
        }
        Ok(members)
    }

    /// The members a flattened field contributes to the object it is flattened into.
    fn flattened(&mut self, ty: &RustType) -> Result<Members, String> {
        match ty {
            RustType::Reference { element, .. } => self.flattened(element),
            RustType::Named { name, arguments } => {
                let name = last_segment(name);
                let arguments = type_arguments(name, arguments)?;
                if matches!(name, "Option" | "Box" | "Arc" | "Cow") {
                    return match arguments.as_slice() {
                        [inner] => self.flattened(inner),
                        _ => Err(format!("{name} requires one type argument")),
                    };
                }
                let api = self.api;
                let record = api
                    .records
                    .get(name)
                    .ok_or_else(|| format!("{name}: flattened record has no declaration"))?;
                match &record.shape {
                    Shape::Alias(inner) => self.flattened(inner),
                    Shape::Struct(Fields::Named(fields)) => {
                        self.members(fields, record.serde.rename_all.as_deref())
                    }
                    Shape::Enum(variants) if record.serde.untagged => {
                        let mut members = Vec::new();
                        for variant in variants.iter().filter(|variant| !variant.serde.skip) {
                            let Fields::Named(fields) = &variant.fields else {
                                return Err(format!(
                                    "{name}: flattened untagged variants must have named fields"
                                ));
                            };
                            let rename = variant
                                .serde
                                .rename_all
                                .as_deref()
                                .or(record.serde.rename_all_fields.as_deref());
                            for member in self.members(fields, rename)? {
                                if !members.contains(&member) {
                                    claim(&mut members, member)?;
                                }
                            }
                        }
                        Ok(members)
                    }
                    _ => Err(format!(
                        "{name}: a flattened field is read as a named record or untagged named variants"
                    )),
                }
            }
            _ => Err("a flattened field is read as a named record".to_owned()),
        }
    }

    /// The static a field or element type is read through, resolved as its TypeScript type is.
    fn ty(&mut self, ty: &RustType) -> Result<String, String> {
        match ty {
            RustType::Reference { element, .. } => self.ty(element),
            RustType::Slice { element } | RustType::Array { element, .. } => self.seq(element),
            RustType::Tuple { elements } if elements.is_empty() => Ok(LEAF.to_owned()),
            RustType::Tuple { elements } => {
                let positions = elements
                    .iter()
                    .map(|element| self.ty(element))
                    .collect::<Result<Vec<_>, _>>()?;
                let reader = format!("TUPLE__{}", positions.join("__"));
                self.define(reader, Node::Tuple(positions))
            }
            RustType::Named { name, arguments } => {
                let name = last_segment(name);
                let arguments = type_arguments(name, arguments)?;
                if primitive_projection(name).is_some() || name.starts_with("NonZero") {
                    return if arguments.is_empty() {
                        Ok(LEAF.to_owned())
                    } else {
                        Err(format!("{name} takes no type arguments"))
                    };
                }
                match (name, arguments.as_slice()) {
                    ("Vec" | "VecDeque" | "BTreeSet" | "HashSet", [element]) => self.seq(element),
                    ("Option" | "Box" | "Arc" | "Cow", [inner]) => self.ty(inner),
                    ("HashMap" | "BTreeMap", [_, value]) => {
                        let value = self.ty(value)?;
                        if value == LEAF {
                            return Ok(LEAF.to_owned());
                        }
                        self.define(format!("MAP__{value}"), Node::Map(value))
                    }
                    (_, []) => self.record(name),
                    (_, _) => Err(format!(
                        "{name}: these type arguments have no reader projection"
                    )),
                }
            }
        }
    }

    fn seq(&mut self, element: &RustType) -> Result<String, String> {
        let element = self.ty(element)?;
        if element == LEAF {
            return Ok(LEAF.to_owned());
        }
        self.define(format!("SEQ__{element}"), Node::Seq(element))
    }
}

/// The fields serde reads and writes.
fn projected(fields: &[Field]) -> Vec<&Field> {
    fields.iter().filter(|field| !field.serde.skip).collect()
}

fn claim(members: &mut Members, member: (String, String)) -> Result<(), String> {
    if let Some((name, _)) = members.iter().find(|(name, _)| *name == member.0) {
        return Err(format!("object member {name} is declared twice"));
    }
    members.push(member);
    Ok(())
}

/// `reader.generated.rs`: the reader of every operation result, and the `Projected` impl that
/// binds each result to it. A result a peer answers is read through its declaration. A result
/// only internal operations answer never crosses a connection: the controller routes it to
/// itself, so its reader is the leaf, which drops nothing, and its decode is the strict one.
pub fn emit(operations: &[Operation], api: &Api) -> Result<String, String> {
    let mut readers = Readers::new(api);
    let mut roots = BTreeMap::new();
    for operation in operations
        .iter()
        .filter(|operation| operation.scope != Scope::Internal)
    {
        let (result, _) = operation_result_record(&operation.result)
            .map_err(|error| format!("{}: {error}", operation.method))?;
        let reader = readers
            .record(&result)
            .map_err(|error| format!("{}: {error}", operation.method))?;
        roots.insert(result, reader);
    }
    for operation in operations
        .iter()
        .filter(|operation| operation.scope == Scope::Internal)
    {
        let (result, _) = operation_result_record(&operation.result)
            .map_err(|error| format!("{}: {error}", operation.method))?;
        roots.entry(result).or_insert_with(|| LEAF.to_owned());
    }
    let mut output = String::from(HEADER);
    output.push_str(
        "//! Every operation result's reader projection (07_api.md, \"Reader projection\"): the\n\
         //! object members each declaration names, as data the client walks before its strict decode.\n\n\
         use super::{Projected, Reader};\n\n",
    );
    for (name, node) in &readers.statics {
        writeln!(output, "static {name}: Reader = {};", expression(node)).unwrap();
    }
    for (result, reader) in &roots {
        let record = &api.records[result];
        let path = record
            .module
            .strip_prefix("cowshed_core")
            .map(|module| format!("crate{module}::{result}"))
            .ok_or_else(|| {
                format!(
                    "{result}: a result declared in {} has no path inside cowshed-core",
                    record.module
                )
            })?;
        writeln!(
            output,
            "\nimpl Projected for {path} {{\n    const READER: &'static Reader = &{reader};\n}}"
        )
        .unwrap();
    }
    Ok(output)
}

fn expression(node: &Node) -> String {
    let members = |members: &Members| {
        members
            .iter()
            .map(|(name, reader)| format!("({name:?}, &{reader})"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    match node {
        Node::Leaf => "Reader::Leaf".to_owned(),
        Node::Seq(element) => format!("Reader::Seq(&{element})"),
        Node::Map(value) => format!("Reader::Map(&{value})"),
        Node::Tuple(positions) => format!(
            "Reader::Tuple(&[{}])",
            positions
                .iter()
                .map(|reader| format!("&{reader}"))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Node::Record(fields) => format!("Reader::Record(&[{}])", members(fields)),
        Node::External(arms) => format!("Reader::External(&[{}])", members(arms)),
        Node::Internal { tag, arms } => format!(
            "Reader::Internal {{ tag: {tag:?}, arms: &[{}] }}",
            members(arms)
        ),
        Node::Adjacent { tag, content, arms } => format!(
            "Reader::Adjacent {{ tag: {tag:?}, content: {content:?}, arms: &[{}] }}",
            members(arms)
        ),
        Node::Untagged(arms) => format!(
            "Reader::Untagged(&[{}])",
            arms.iter()
                .map(|fields| format!("&[{}]", members(fields)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// The TypeScript readers the native adapters call (`validators.generated.ts`): typia's
/// `assert` with its `prune`, so an object member the declaration does not name is dropped, at
/// every depth, instead of refused. A declaration with no declared object inside it has nothing
/// to drop, and its reader is its strict parser.
pub fn typescript(api: &Api, reads: &BTreeSet<(String, ResultShape)>) -> Result<String, String> {
    let mut readers = Readers::new(api);
    let mut output = String::new();
    for (rust, shape) in reads {
        let record = api
            .records
            .get(rust)
            .ok_or_else(|| format!("API type {rust} has no declaration"))?;
        let name = record.projection.name.as_deref().unwrap_or(rust);
        let (suffix, ty) = match shape {
            ResultShape::Record => ("", format!("Api.{name}")),
            ResultShape::List => ("List", format!("readonly Api.{name}[]")),
            ResultShape::Optional => ("Option", format!("Api.{name} | null")),
        };
        if readers.is_leaf(rust)? {
            writeln!(
                output,
                "export const read{name}{suffix} = parse{name}{suffix};\n"
            )
            .unwrap();
            continue;
        }
        match shape {
            ResultShape::Record | ResultShape::List => {
                writeln!(
                    output,
                    "export const assertPrune{name}{suffix} = typia.plain.createAssertPrune<{ty}>();\n\
                     export const read{name}{suffix} = (json: string): {ty} => assertPrune{name}{suffix}(JSON.parse(json));\n"
                )
                .unwrap();
            }
            ResultShape::Optional => {
                writeln!(
                    output,
                    "export const assertPrune{name}Present = typia.plain.createAssertPrune<Api.{name}>();\n\
                     export const read{name}Option = (json: string): {ty} => {{\n  \
                     const value: unknown = JSON.parse(json);\n  \
                     return value === null ? null : assertPrune{name}Present(value);\n}};\n"
                )
                .unwrap();
            }
        }
    }
    Ok(output)
}
