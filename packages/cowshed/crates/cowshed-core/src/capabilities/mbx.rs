    #[test]
    fn installed_mbx_enables_cargo_without_project_opt_in() {
        use cowshed_os::test_backstop::CommandBackstop as _;
        let fixture = super::super::test_support::Fixture::new();
        fixture.files(&["Cargo.toml"]);
        let installed = install_fixture_mbx(&fixture);
        let build_cache = fixture.root.join("build-cache");
        let context = DetectionContext {
            build_cache: Some(&build_cache),
            ..fixture.context()
        };
        let contribution = DETECTOR
            .detect(&context)
            .unwrap()
            .expect("installed mbx enables Cargo without discovery or a devenv pin");
        assert_eq!(
            contribution.env.get("COWSHED_CARGO_ROUTE"),
            Some(&EnvAction::Own(cargo_route(&fixture.home).into_os_string()))
        );
        assert_eq!(
            contribution.env.get("MBX_SCHEDULER_TESTS"),
            Some(&EnvAction::Own("1".into()))
        );
        let EnvAction::Own(route) = &contribution.env[CARGO_ROUTE_ENV] else {
            panic!("the installed Cargo route must be capability-owned");
        };
        let route = PathBuf::from(route);
        let toolchain = fixture.root.join("project-toolchain");
        std::fs::create_dir_all(&toolchain).unwrap();
        std::os::unix::fs::symlink(route.join("cargo"), toolchain.join("cargo")).unwrap();
        let path = std::env::join_paths([
            route.clone(),
            toolchain,
            PathBuf::from("/usr/bin"),
            PathBuf::from("/bin"),
        ])
        .unwrap();
        let output = std::process::Command::new("sh")
            .args(["-c", "command -v cargo; command -v mbx"])
            .env("PATH", path)
            .output_bounded()
            .unwrap();
        assert!(output.status.success(), "{output:?}");
        assert_eq!(
            String::from_utf8(output.stdout).unwrap(),
            format!(
                "{}\n{}\n",
                route.join("cargo").display(),
                route.join("mbx").display()
            )
        );
        assert_eq!(
            std::fs::read_to_string(route.join("mbx-target")).unwrap(),
            installed.to_str().unwrap()
        );
        assert_eq!(
            contribution.env.get("MBX_CACHE_DIR"),
            Some(&EnvAction::Own(build_cache.join("mbx").into_os_string()))
        );
        assert_eq!(
            contribution.env.get("MBX_SESSION_ROOT"),
            Some(&EnvAction::Own(
                context.runtime_dir.join("mbx").into_os_string()
            ))
        );
        assert!(HOST_ENVIRONMENT.contains(&"MBX_SESSION_ROOT"));
        assert!(
            contribution
                .daemon_isolation
                .directories
                .contains(&context.runtime_dir.join("mbx"))
        );
        for unset in [
            "RUSTC_WRAPPER",
            "RUSTC_WORKSPACE_WRAPPER",
            "MBX_TARGET_ROOT",
            "MBX_DISABLE",
        ] {
            assert_eq!(
                contribution.env.get(unset),
                Some(&EnvAction::Unset),
                "{unset}"
            );
        }
        assert!(contribution.grants.contains(&CapabilityGrant {
            path: build_cache.join("mbx"),
            scope: GrantScope::Subtree,
            access: GrantAccess::ReadWrite,
        }));
        assert!(
            contribution
                .grants
                .iter()
                .filter(|grant| grant.access != GrantAccess::ReadMetadata)
                .all(|grant| grant.path.starts_with(build_cache.join("mbx"))
                    || grant.path == cargo_route(&fixture.home)
                    || grant.path == installed
                    || grant.path == host_link(&fixture.home)
                    || grant.path == host_settings_file(&fixture.home)
                    || grant.path
                        == build_cache.join(crate::storage::bootstrap::VOLUME_MARKER_FILE)),
            "{:?}",
            contribution.grants
        );
        assert_eq!(
            contribution.daemon_isolation.discard_at_mint,
            [PathBuf::from(".cowshed/run/mbx"), PathBuf::from("target")]
        );
    }

    /// The host's scheduler settings come from the installed mbx's own settings interface, with
    /// none of this process's environment but HOME, and an unset one stays unset; `"none"` memory
    /// is the unscheduled finding.
    #[test]
    fn the_host_scheduler_is_read_through_the_installed_mbx_alone() {
        use std::os::unix::fs::PermissionsExt as _;
        let root =
            std::env::temp_dir().join(format!("cowshed-mbx-settings-{}", std::process::id()));
        std::fs::create_dir_all(&root).unwrap();
        let mbx = root.join("mbx");
        std::fs::write(
            &mbx,
            "#!/bin/sh\n[ -z \"$MBX_SCHEDULER_CPUS\" ] || exit 9\ncase \"$3\" in\nscheduler.cpus) echo 8 ;;\nscheduler.memory) echo none ;;\nesac\n",
        )
        .unwrap();
        std::fs::set_permissions(&mbx, std::fs::Permissions::from_mode(0o755)).unwrap();
        // SAFETY: this test alone names the variable, and only to prove it never reaches mbx.
        unsafe { std::env::set_var("MBX_SCHEDULER_CPUS", "99") };
        let read = read_host_scheduler(&mbx, &root).unwrap();
        unsafe { std::env::remove_var("MBX_SCHEDULER_CPUS") };
        assert_eq!(
            read,
            HostScheduler {
                cpus: Some("8".into()),
                reserve_cpus: None,
                memory: Some("none".into()),
            }
        );
        assert!(read.memory_unscheduled());
        assert!(!HostScheduler::default().memory_unscheduled());
        let refusal = Admission::MemoryUnscheduled
            .refusal(Path::new("/pinned/mbx-1.28.0/bin/mbx"))
            .unwrap();
        assert!(
            refusal.message.starts_with("mbx-memory-unscheduled"),
            "{}",
            refusal.message
        );
        std::fs::remove_dir_all(&root).unwrap();
    }

