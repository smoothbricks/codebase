    #[test]
    fn cargo_disabled_and_directory_selection_apply_to_mbx() {
        use super::super::CapabilityOverride;
        use std::collections::BTreeMap;
        let fixture = super::super::test_support::Fixture::new();
        fixture.files(&["Cargo.toml", "rust/Cargo.toml"]);
        std::fs::create_dir_all(fixture.root.join("empty")).unwrap();
        install_fixture_mbx(&fixture);
        let cache = fixture.root.join("build-cache");
        let context = DetectionContext {
            build_cache: Some(&cache),
            ..fixture.context()
        };
        for (disabled, directory, mbx_directory, active) in [
            (true, None, None, false),
            (false, Some("empty"), None, false),
            (false, Some("empty"), Some("rust"), false),
            (false, Some("rust"), None, true),
        ] {
            let mut overrides = BTreeMap::from([(
                CapabilityId::Cargo,
                CapabilityOverride {
                    disabled,
                    directory: directory.map(PathBuf::from),
                },
            )]);
            if let Some(directory) = mbx_directory {
                overrides.insert(
                    CapabilityId::Mbx,
                    CapabilityOverride {
                        disabled: false,
                        directory: Some(PathBuf::from(directory)),
                    },
                );
            }
            let found = super::super::detect(&context, &overrides).unwrap();
            assert_eq!(
                found.active.contains(&CapabilityId::Mbx),
                active,
                "{disabled} {directory:?}"
            );
            let mut config = format!("[capabilities.cargo]\ndisabled = {disabled}\n");
            if let Some(directory) = directory {
                config.push_str(&format!("directory = \"{directory}\"\n"));
            }
            if let Some(directory) = mbx_directory {
                config.push_str(&format!(
                    "[capabilities.mbx]\ndirectory = \"{directory}\"\n"
                ));
            }
            std::fs::write(fixture.root.join(".cowshed.toml"), config).unwrap();
            assert_eq!(
                checkout_verdict(&fixture.root, &fixture.home, Some(&cache))
                    .unwrap()
                    .is_some(),
                active,
                "admission {disabled} {directory:?}"
            );
            if active {
                assert!(
                    found
                        .contribution
                        .daemon_isolation
                        .discard_at_mint
                        .contains(&PathBuf::from("rust/target"))
                );
            }
        }
    }
