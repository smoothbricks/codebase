        // The dependency's setup interface supplies a shim and an executable sidecar.
        std::fs::write(route.join("cargo"), "#!/bin/sh\nexit 0\n").unwrap();
        std::fs::set_permissions(route.join("cargo"), std::fs::Permissions::from_mode(0o755))
            .unwrap();
        std::fs::write(
            route.join("mbx-target"),
            executable.as_os_str().as_encoded_bytes(),
        )
        .unwrap();
