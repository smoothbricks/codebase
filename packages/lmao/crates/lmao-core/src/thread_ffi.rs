/// Cold dynamic-name variant. The UTF-8 name is copied once into `SharedStr`.
/// # Safety
/// `handle` must be a live uniquely owned handle. Both byte ranges must be
/// readable for the duration of this call; null pointers are valid only with
/// zero lengths.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_open_span_dynamic(
    handle: *mut ThreadSpanBufferHandle,
    trace_ptr: *const u8,
    trace_len: usize,
    parent_thread_id: u64,
    parent_span_id: u32,
    name_ptr: *const u8,
    name_len: usize,
    timestamp: i64,
    line: u32,
) -> u64 {
    let Some(buffer) = as_buffer(handle) else {
        return 0;
    };
    let Some(trace_id) = parse_trace(trace_ptr, trace_len) else {
        return 0;
    };
    let Some(name) = (unsafe { parse_text(name_ptr, name_len) }) else {
        return 0;
    };
    let Ok(span_id) = buffer.open_span(
        trace_id,
        parent_thread_id,
        parent_span_id,
        TextInput::Dynamic(name),
        timestamp,
        line,
    ) else {
        return 0;
    };
    let Some(row) = buffer.start_row(span_id) else {
        return 0;
    };
    let row = u32::try_from(row).expect("thread buffer rows fit u32");
    packed_row(span_id, row)
}

