fn write_value(buffer: &mut ThreadSpanBuffer, row: u32, ordinal: u16, kind: u8, value: u64) -> u8 {
    let Some(value) = buffer.decode_abi_value(kind, value) else {
        return 1;
    };
    buffer.write_attr(row, ordinal, value).is_err() as u8
}

