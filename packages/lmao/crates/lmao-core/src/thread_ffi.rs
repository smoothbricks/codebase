/// Warmed log path: `message_ordinal` is from `thread_span_buffer_intern`.
/// # Safety
/// `handle` must be a live uniquely owned handle.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_append_log(
    handle: *mut ThreadSpanBufferHandle,
    span_id: u32,
    entry_type: u8,
    message_ordinal: u32,
    timestamp: i64,
    line: u32,
) -> u64 {
    let Some(buffer) = as_buffer(handle) else {
        return 0;
    };
    let Some(entry_type) = EntryType::from_u8(entry_type) else {
        return 0;
    };
    let Ok(row) = buffer.append_log_interned(span_id, entry_type, message_ordinal, line, timestamp)
    else {
        return 0;
    };
    packed_row(span_id, row)
}

