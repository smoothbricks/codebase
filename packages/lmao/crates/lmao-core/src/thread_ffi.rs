//! Canonical scalar ABI for [`crate::ThreadSpanBuffer`].
//!
//! Bindings (JSC and Wasm) only re-export these symbols. Strings cross the ABI
//! as UTF-8 pointer/length pairs on cold dynamic entrypoints; warmed writers use
//! an intern ordinal and a single scalar value. Packed-u64 row endpoints return
//! zero on failure; u8 status endpoints return zero on success and nonzero on
//! failure.

use crate::arena::TextInput;
use crate::columns::FieldMeta;
use crate::entry_type::EntryType;
use crate::identity::TraceId;
use crate::packed_header::VocabularyId;
use crate::thread_buffer::{ColumnValue, ThreadSpanBuffer};
use std::sync::Arc;

/// Opaque pointer type used by native and Wasm callers.
#[repr(C)]
pub struct ThreadSpanBufferHandle {
    _private: [u8; 0],
}

fn as_buffer<'a>(handle: *mut ThreadSpanBufferHandle) -> Option<&'a mut ThreadSpanBuffer> {
    if handle.is_null() {
        return None;
    }
    // SAFETY: handles are returned by `thread_span_buffer_new*` and remain
    // uniquely owned by the caller until `thread_span_buffer_free`.
    Some(unsafe { &mut *(handle.cast::<ThreadSpanBuffer>()) })
}

fn parse_trace(ptr: *const u8, len: usize) -> Option<TraceId> {
    if len > 0 && ptr.is_null() {
        return None;
    }
    // SAFETY: callers promise `ptr..ptr+len` is readable UTF-8 storage for the
    // duration of this call; a zero-length null pointer is accepted.
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    let value = std::str::from_utf8(bytes).ok()?;
    TraceId::new(Arc::<str>::from(value)).ok()
}

/// Borrow the caller's UTF-8 for the duration of one ABI call.
///
/// The borrow is unbounded, which is sound only because every caller hands the
/// result straight to a row store that copies it into its arena before
/// returning. The bytes belong to the caller and are not retained: that is the
/// same discipline the reverse ABI runs in `containium-realm-spans`.
///
/// # Safety
/// `ptr..ptr + len` must be readable until the returned borrow is dropped.
unsafe fn parse_text<'a>(ptr: *const u8, len: usize) -> Option<&'a str> {
    if len > 0 && ptr.is_null() {
        return None;
    }
    // SAFETY: callers promise `ptr..ptr+len` is readable storage for this call.
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    ThreadSpanBuffer::utf8(bytes).ok()
}

fn packed_row(span_id: u32, row: u32) -> u64 {
    (u64::from(span_id) << 32) | u64::from(row)
}

fn valid_capacity(capacity: usize) -> bool {
    capacity.is_power_of_two() && (crate::MIN_CAPACITY..=crate::MAX_CAPACITY).contains(&capacity)
}

/// Allocate a schema-less handle. Use `thread_span_buffer_new_with_fields` for
/// typed schema attributes; both constructors share the exact same row store.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub extern "C" fn thread_span_buffer_new(
    thread_id: u64,
    capacity: usize,
) -> *mut ThreadSpanBufferHandle {
    if !valid_capacity(capacity) {
        return std::ptr::null_mut();
    }
    Box::into_raw(Box::new(ThreadSpanBuffer::new(thread_id, capacity, &[])))
        .cast::<ThreadSpanBufferHandle>()
}

/// Allocate a handle with schema metadata generated by the host build.
///
/// # Safety
/// `fields` must either be null when `field_count == 0`, or point to a
/// `'static` contiguous `FieldMeta` table. The table remains borrowed by every
/// overflow block for the handle's lifetime.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_new_with_fields(
    thread_id: u64,
    capacity: usize,
    fields: *const FieldMeta,
    field_count: usize,
) -> *mut ThreadSpanBufferHandle {
    if !valid_capacity(capacity) || (field_count > 0 && fields.is_null()) {
        return std::ptr::null_mut();
    }
    // SAFETY: required by this function's contract; zero count may use a null
    // pointer and is represented by the static empty slice.
    let fields: &'static [FieldMeta] = if field_count == 0 {
        &[]
    } else {
        unsafe { std::slice::from_raw_parts(fields, field_count) }
    };
    Box::into_raw(Box::new(ThreadSpanBuffer::new(thread_id, capacity, fields)))
        .cast::<ThreadSpanBufferHandle>()
}

/// Release a handle. Null is accepted so teardown paths can be idempotent.
/// # Safety
/// `handle` must be null or a live handle returned by a constructor and not
/// previously freed.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_free(handle: *mut ThreadSpanBufferHandle) {
    if !handle.is_null() {
        // SAFETY: the pointer was allocated by one of the constructors and is
        // consumed exactly once here.
        drop(unsafe { Box::from_raw(handle.cast::<ThreadSpanBuffer>()) });
    }
}

/// Intern one dynamic UTF-8 value. The ordinal is stable across overflow
/// blocks and valid until the handle is freed; zero denotes failure.
/// # Safety
/// `handle` must be a live uniquely owned handle. When `len > 0`, `ptr` must
/// point to readable storage for `len` bytes for the duration of this call.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_intern(
    handle: *mut ThreadSpanBufferHandle,
    ptr: *const u8,
    len: usize,
) -> u32 {
    let Some(buffer) = as_buffer(handle) else {
        return 0;
    };
    if len > 0 && ptr.is_null() {
        return 0;
    }
    // SAFETY: caller owns readable bytes for this call; null is valid for len 0.
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    buffer.intern_utf8(bytes).unwrap_or(0)
}

/// Open a span whose name is an intern ordinal. The return packs
/// `(span_id << 32) | start_row`; zero denotes failure.
/// # Safety
/// `handle` must be a live uniquely owned handle. `trace_ptr` must point to
/// readable storage for `trace_len` bytes, unless the length is zero.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_open_span(
    handle: *mut ThreadSpanBufferHandle,
    trace_ptr: *const u8,
    trace_len: usize,
    parent_thread_id: u64,
    parent_span_id: u32,
    name_ordinal: u32,
    timestamp: i64,
    line: u32,
) -> u64 {
    let Some(buffer) = as_buffer(handle) else {
        return 0;
    };
    let Some(trace_id) = parse_trace(trace_ptr, trace_len) else {
        return 0;
    };
    let Ok(span_id) = buffer.open_span_interned(
        trace_id,
        parent_thread_id,
        parent_span_id,
        name_ordinal,
        timestamp,
        line,
    ) else {
        return 0;
    };
    let Some(row) = buffer.start_row(span_id) else {
        return 0;
    };
    let row = u32::try_from(row).expect("thread buffer rows fit u32");
    packed_row(span_id, row)
}

