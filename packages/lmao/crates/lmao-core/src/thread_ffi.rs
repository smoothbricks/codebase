/// # Safety
/// `handle` must be a live uniquely owned handle.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_write_tag(
    handle: *mut ThreadSpanBufferHandle,
    span_id: u32,
    ordinal: u16,
    kind: u8,
    value: u64,
) -> u8 {
    let Some(buffer) = as_buffer(handle) else {
        return 1;
    };
    let Some(row) = buffer
        .start_row(span_id)
        .and_then(|row| u32::try_from(row).ok())
    else {
        return 1;
    };
    write_value(buffer, row, ordinal, kind, value)
}

/// # Safety
/// `handle` must be a live uniquely owned handle.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_set_scope(
    handle: *mut ThreadSpanBufferHandle,
    span_id: u32,
    ordinal: u16,
    kind: u8,
    value: u64,
) -> u8 {
    let Some(buffer) = as_buffer(handle) else {
        return 1;
    };
    let Some(index) = usize::from(ordinal).checked_sub(crate::SYSTEM_COLUMN_COUNT) else {
        return 1;
    };
    let Some(field) = buffer.schema_fields().get(index) else {
        return 1;
    };
    let Some(value) = buffer.decode_abi_value(kind, value) else {
        return 1;
    };
    let scope_value = match value {
        ColumnValue::Number(value) => crate::ScopeValue::Number(value),
        ColumnValue::Uint64(value) => crate::ScopeValue::Uint64(value),
        ColumnValue::Boolean(value) => crate::ScopeValue::Boolean(value),
        ColumnValue::Enum(value) => crate::ScopeValue::EnumIndex(value),
        // A scope is shared between spans by refcount, so it cannot carry an
        // arena handle. The cold path takes one owned copy; rows re-intern it
        // into their own arena at materialization, which is a hash hit.
        ColumnValue::Text(ordinal) => {
            let Some(text) = buffer.interned(ordinal) else {
                return 1;
            };
            crate::ScopeValue::Text(std::borrow::Cow::Owned(text.to_owned()))
        }
    };
    let update = [(field.name, Some(scope_value))];
    buffer.set_scope(span_id, &update).is_err() as u8
}

/// Release every row and span on a handle, keeping its interned vocabulary.
///
/// Returns zero on success and nonzero when the handle is null.
///
/// # Safety
/// `handle` must be null or a live handle returned by a constructor and not
/// previously freed.
#[cfg_attr(not(target_family = "wasm"), unsafe(no_mangle))]
pub unsafe extern "C" fn thread_span_buffer_reset(handle: *mut ThreadSpanBufferHandle) -> u8 {
    let Some(buffer) = as_buffer(handle) else {
        return 1;
    };
    buffer.reset();
    0
}

/// Complete a span with the caller's entry type.
///
/// The generic endpoint preserves the distinction between handled errors and
/// thrown exceptions that the end_ok/end_err pair cannot carry.
